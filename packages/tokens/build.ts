/**
 * Writes skins.css: every token with its default Hue, dark values, wide gamut values,
 * and the Tailwind theme that turns them into utilities such as `bg-sk-accent`.
 */
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { DEFAULT_PRESET, STOPS, createHue, neutrals, toCss } from "../hue/src/index.ts";

const out = fileURLToPath(new URL("./skins.css", import.meta.url));

const colorNames = [
  ...Object.keys(neutrals.light).filter((k) => !k.startsWith("shadow-") && k !== "edge-light"),
  ...STOPS.map((s) => `hue-${s}`),
  "hue-deep", "hue-2", "hue-3",
  "accent", "accent-hover", "accent-active", "accent-fg",
  "indicator", "indicator-fg",
  "accent-subtle", "accent-subtle-fg", "accent-border",
  "link", "ring",
];
const shadowNames = Object.keys(neutrals.light).filter((k) => k.startsWith("shadow-")).map((k) => k.slice(7));

const base = `:root {
  --sk-font-sans: ui-sans-serif, system-ui, sans-serif;
  --sk-font-display: var(--sk-font-sans);
  --sk-font-mono: ui-monospace, "SF Mono", Menlo, monospace;

  --sk-ease-out: cubic-bezier(0.22, 1, 0.36, 1);
  --sk-motion-fast: 100ms;
  --sk-motion-base: 150ms;
  --sk-motion-slow: 220ms;
  --sk-motion-fast-exit: 60ms;
  --sk-motion-base-exit: 120ms;
  --sk-motion-slow-exit: 160ms;
}`;

const theme = `@custom-variant dark (&:where(.dark, .dark *, [data-theme="dark"], [data-theme="dark"] *));

@theme inline {
${colorNames.map((n) => `  --color-sk-${n}: var(--sk-${n});`).join("\n")}

${shadowNames.map((n) => `  --shadow-sk-${n}: var(--sk-shadow-${n});`).join("\n")}
  --shadow-sk-edge-light: var(--sk-edge-light);

  --font-sk-sans: var(--sk-font-sans);
  --font-sk-display: var(--sk-font-display);
  --font-sk-mono: var(--sk-font-mono);

  --ease-sk-out: var(--sk-ease-out);
}`;

const css = [
  "/* Generated by packages/tokens/build.ts. Do not edit by hand. */",
  base,
  toCss(createHue(DEFAULT_PRESET.color)),
  theme,
].join("\n\n") + "\n";

if (/[\u2013\u2014]/.test(css)) throw new Error("skins.css contains a long dash");
writeFileSync(out, css);
console.log(`Wrote ${out}`);
